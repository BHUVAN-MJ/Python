
# 3.While Loop, Variables & Operators

"""
  Write a Python program that:
    1.Creates a variable power = 1.
    2.Uses a while loop that runs as long as power < 100.
    3.Inside the loop, multiplies power by 2 and prints the result.
  
    
"""

power = 1

while power < 100:
    power *= 2
    print(power)