
# 4.While Loop & Tuple Indexing

"""
 Write a Python program that:
    1.Creates a Tuple: colors = ("Red", "Green", "Blue").
    2.Uses a while loop that runs as long as the index is less than 3.
    3.Inside the loop, print the color at that index, then add 1 to the index.

      
"""

colors =("red","green","blue")

index =0

while index < 3:
    print(colors[index])
    index += 1

    