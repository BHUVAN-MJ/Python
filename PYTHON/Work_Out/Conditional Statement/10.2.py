# Meal Time Checker:

"""
Create a program that checks the time of day (24-hour format) and prints whether it's time for breakfast, 
lunch, or dinner.
Breakfast: 8 AM
Lunch: 1 PM
Dinner: 8 PM
If none of these times, print "It's not meal time."

"""

time=1

if time==8:
    print("it's time for breakfast!")
elif time==1:
    print("It's time for lunch!")
elif time==20:
    print("It's time for dinner!")
else:
    print("it's not time for a meal")